/// What to add to the dependencies for the artifact. A core artifact is noted as part of
/// camel-core.
///
/// (The Java version said "to the classpath".)
///
/// # Examples
///
/// ```
/// use camel_util::artifact_utils::dependency_hint;
/// assert_eq!("add camel-saxon to the dependencies", dependency_hint("camel-saxon"));
/// assert_eq!("add camel-support (part of camel-core) to the dependencies", dependency_hint("camel-support"));
/// ```
pub fn dependency_hint(artifact_id: &str) -> String {
    if artifact_id.trim().is_empty() {
        return String::new();
    }
    if is_core_artifact(artifact_id) {
        format!("add {artifact_id} (part of camel-core) to the dependencies")
    } else {
        format!("add {artifact_id} to the dependencies")
    }
}

fn is_core_artifact(a: &str) -> bool {
    a.starts_with("camel-core-")
        || matches!(
            a,
            "camel-core"
                | "camel-base"
                | "camel-base-engine"
                | "camel-support"
                | "camel-api"
                | "camel-util"
        )
}

