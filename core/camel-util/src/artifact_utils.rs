fn hint(name: &str, kind: &str, table: &BTreeMap<&'static str, &'static str>) -> String {
    if name.trim().is_empty() {
        return String::new();
    }
    if let Some(artifact) = table.get(name) {
        return format!(
            " (the {name} {kind} is in {artifact}; {})",
            dependency_hint(artifact)
        );
    }
    match closest(name, table.keys().copied()) {
        Some(best) => format!(" (not a built-in Camel {kind}; did you mean '{best}'?)"),
        None => format!(" (not a built-in Camel {kind})"),
    }
}

/// The candidate closest to the name, case-insensitively, when it is within a few edits (one
/// for names up to three characters, two, or a third of the name's length for longer names).
///
/// Of candidates at the same distance the one sharing the longer prefix with the name wins, as
/// typos are seldom in the first letters (`htps` is `https`, not `ftps`); when that still ties
/// there is no answer, as a wrong guess is worse than none.
///
/// # Returns
///
/// The closest candidate, or `None` if none is close enough or the closest is ambiguous.
pub fn closest<'a, I: IntoIterator<Item = &'a str>>(name: &str, candidates: I) -> Option<&'a str> {
    if name.trim().is_empty() {
        return None;
    }
    let len = name.chars().count();
    let threshold = if len <= 3 { 1 } else { 2.max(len / 3) };
    let n = name.to_lowercase();
    let mut best: Option<&'a str> = None;
    let mut best_distance = usize::MAX;
    let mut best_prefix: isize = -1;
    let mut tie = false;
    for candidate in candidates {
        let c = candidate.to_lowercase();
        let d = distance(&n, &c);
        if d > threshold || d > best_distance {
            continue;
        }
        let prefix = common_prefix(&n, &c) as isize;
        if d < best_distance || prefix > best_prefix {
            best = Some(candidate);
            best_distance = d;
            best_prefix = prefix;
            tie = false;
        } else if prefix == best_prefix {
            tie = true;
        }
    }
    if tie {
        None
    } else {
        best
    }
}

fn common_prefix(a: &str, b: &str) -> usize {
    a.chars().zip(b.chars()).take_while(|(x, y)| x == y).count()
}

/// The Damerau-Levenshtein distance (optimal string alignment): insertions, deletions,
/// substitutions and transpositions of adjacent characters each count as one edit.
pub fn distance(a: &str, b: &str) -> usize {
    let a: Vec<char> = a.chars().collect();
    let b: Vec<char> = b.chars().collect();
    let (n, m) = (a.len(), b.len());
    if n == 0 {
        return m;
    }
    if m == 0 {
        return n;
    }
    let mut d = vec![vec![0usize; m + 1]; n + 1];
    for (i, row) in d.iter_mut().enumerate() {
        row[0] = i;
    }
    for (j, cell) in d[0].iter_mut().enumerate() {
        *cell = j;
    }
    for i in 1..=n {
        for j in 1..=m {
            let cost = usize::from(a[i - 1] != b[j - 1]);
            d[i][j] = (d[i - 1][j] + 1)
                .min(d[i][j - 1] + 1)
                .min(d[i - 1][j - 1] + cost);
            if i > 1 && j > 1 && a[i - 1] == b[j - 2] && a[i - 2] == b[j - 1] {
                d[i][j] = d[i][j].min(d[i - 2][j - 2] + 1);
            }
        }
    }
    d[n][m]
}

